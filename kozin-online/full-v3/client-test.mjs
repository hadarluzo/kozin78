import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('../../online.html',import.meta.url),'utf8');
const a=html.indexOf('function syncAccountProfile(){');
const b=html.indexOf('\nconst announce=',a);
assert(a>0&&b>a,'profile sync function present');
assert(html.includes('id="nickname" readonly'),'online nickname comes from account');
assert(html.includes('<select id="hero" aria-label="בחר דמות שבבעלותך"></select>'),'no unlocked static options');
const code=html.slice(a,b);
const labels={luzo:'הדר',tzippy:'ציפי',michael:'מיכאל'};
const foreignOwned=vm.runInNewContext("new Set(['luzo','tzippy'])");
const options=[],hero={value:'',replaceChildren(){options.length=0},append(opt){options.push(opt)}};
const els={hero,nickname:{value:''},accountNote:{textContent:''}};
const fakeDocument={createElement(tag){assert.equal(tag,'option');return {value:'',textContent:''}}};
const frame={game:{wallet:{owned:foreignOwned,selected:'tzippy',cloudUserName:'שם מהחשבון',name:'שחקן חדש',user:'uid'}}};
const sync=new Function('frame','$','document','HERO_LABELS',code+';return syncAccountProfile;')(frame,id=>els[id],fakeDocument,labels);
sync();
assert.deepEqual(options.map(x=>x.value),['luzo','tzippy'],'roster must be cross-frame and ownership based');
assert.equal(hero.value,'tzippy');
assert.equal(els.nickname.value,'שם מהחשבון');
assert(!options.some(x=>x.value==='michael'));
frame.game.wallet={owned:vm.runInNewContext("new Set(['luzo'])"),selected:'luzo',cloudUserName:null,name:'שחקן חדש',user:null};
sync();
assert.equal(els.nickname.value,'אורח');
assert.deepEqual(options.map(x=>x.value),['luzo']);
console.log('PASS client cross-frame owned-hero filtering and account nickname');
